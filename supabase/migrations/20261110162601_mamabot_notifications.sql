create table if not exists public.users (
    id bigint generated by default as identity primary key,
    phone_number text not null unique,
    name text,
    preferred_lang text not null default 'english',
    preferred_channel text not null default 'whatsapp',
    last_intent text,
    due_date date,
    reminders_enabled boolean not null default false,
    consent_at timestamptz,
    consent_source text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.users
    add column if not exists name text,
    add column if not exists preferred_lang text not null default 'english',
    add column if not exists preferred_channel text not null default 'whatsapp',
    add column if not exists last_intent text,
    add column if not exists due_date date,
    add column if not exists reminders_enabled boolean not null default false,
    add column if not exists consent_at timestamptz,
    add column if not exists consent_source text,
    add column if not exists created_at timestamptz not null default now(),
    add column if not exists updated_at timestamptz not null default now();

create table if not exists public.messages (
    id bigint generated by default as identity primary key,
    phone_number text not null,
    direction text not null,
    content text,
    intent text,
    channel text,
    language text,
    provider_message_id text,
    created_at timestamptz not null default now()
);

alter table public.messages
    add column if not exists phone_number text,
    add column if not exists direction text,
    add column if not exists content text,
    add column if not exists intent text,
    add column if not exists channel text,
    add column if not exists language text,
    add column if not exists provider_message_id text,
    add column if not exists created_at timestamptz not null default now();

create table if not exists public.appointments (
    id uuid primary key default gen_random_uuid(),
    phone_number text not null references public.users(phone_number) on delete cascade,
    appointment_at timestamptz not null,
    clinic_name text,
    idempotency_key text not null unique,
    created_at timestamptz not null default now()
);

alter table public.appointments
    add column if not exists idempotency_key text;
create unique index if not exists appointments_idempotency_key_idx
    on public.appointments (idempotency_key)
    where idempotency_key is not null;

create table if not exists public.reminders (
    id uuid primary key default gen_random_uuid(),
    phone_number text not null references public.users(phone_number) on delete cascade,
    appointment_id uuid references public.appointments(id) on delete cascade,
    category text not null check (
        category in ('weekly_pregnancy', 'anc_appointment', 'general')
    ),
    channel text not null default 'whatsapp' check (channel = 'whatsapp'),
    content text not null,
    scheduled_at timestamptz not null,
    status text not null default 'pending' check (
        status in ('pending', 'sending', 'sent', 'failed', 'cancelled')
    ),
    idempotency_key text not null unique,
    provider_message_id text,
    send_attempts integer not null default 0,
    last_error text,
    claimed_at timestamptz,
    sent_at timestamptz,
    created_at timestamptz not null default now()
);

alter table public.reminders
    drop constraint if exists reminders_status_check;
alter table public.reminders
    add constraint reminders_status_check
    check (status in ('pending', 'sending', 'sent', 'failed', 'cancelled'));

create index if not exists reminders_due_idx
    on public.reminders (scheduled_at)
    where status = 'pending';

create table if not exists public.sms_delivery_reports (
    webhook_id bigint primary key,
    message_id bigint not null,
    campaign_id bigint,
    phone text not null,
    network text,
    status text not null,
    error text,
    delivered_at timestamptz,
    payload jsonb not null,
    received_at timestamptz not null default now()
);

create or replace function public.claim_due_reminders(p_limit integer default 50)
returns setof public.reminders
language sql
security invoker
set search_path = ''
as $$
    with due as (
        select r.id
        from public.reminders as r
        where r.status = 'pending'
          and r.scheduled_at <= now()
        order by r.scheduled_at
        for update skip locked
        limit least(greatest(coalesce(p_limit, 50), 1), 100)
    )
    update public.reminders as r
    set status = 'sending',
        claimed_at = now(),
        send_attempts = r.send_attempts + 1
    from due
    where r.id = due.id
    returning r.*;
$$;

